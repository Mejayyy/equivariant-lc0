"""G_chess = Z/2Z x Z/2Z = {e, sigma_h, sigma_c, sigma_h o sigma_c} and
its subgroup SG_chess = {e, sigma_c} ~ Z/2Z.

Fixed enumeration of G_chess (used by every other module):
    0 = e
    1 = sigma_h    (file flip; A <-> H)
    2 = sigma_c    (rank flip + channel swap of our/opp + side-to-move flip)
    3 = sigma_hc   (sigma_h composed with sigma_c)

SG_chess is the (color-swap) subgroup generated by sigma_c. Local
enumeration of its elements:
    0 = e
    1 = sigma_c

Both groups are abelian and self-inverse (Klein four / Z_2 respectively).

A `GroupDef` value collects everything the rest of the code base needs
to handle a group generically:

    - `name`              : human label ('gchess' / 'sgchess')
    - `order`             : |G|
    - `composition_table` : i o j (apply j first, then i), in the
                            group's own LOCAL enumeration
    - `to_gchess`         : local index -> GChess element (int). Used to
                            invoke the existing chess-aware actions in
                            ``symmetry.actions`` from primitives that
                            only know about the abstract group.

`GCHESS_GROUP` and `SGCHESS_GROUP` are the two values in use. The G-CNN
primitives (`LiftingConv`, `GConv`, ...) and the equivariant heads
accept a `group` keyword that defaults to `GCHESS_GROUP` for
backward compatibility.
"""

from dataclasses import dataclass
from enum import IntEnum
from typing import Tuple


class GChess(IntEnum):
    E = 0
    SIGMA_H = 1
    SIGMA_C = 2
    SIGMA_HC = 3


class SGChess(IntEnum):
    """Local enumeration of the SG_chess subgroup = {e, sigma_c}."""

    E = 0
    SIGMA_C = 1


ELEMENTS = (GChess.E, GChess.SIGMA_H, GChess.SIGMA_C, GChess.SIGMA_HC)
ORDER = 4

# COMPOSITION_TABLE[i][j] = i o j (apply j first, then i).
COMPOSITION_TABLE = (
    (0, 1, 2, 3),
    (1, 0, 3, 2),
    (2, 3, 0, 1),
    (3, 2, 1, 0),
)

SGCHESS_ELEMENTS = (SGChess.E, SGChess.SIGMA_C)
SGCHESS_ORDER = 2

# SG_chess as Z_2: e and sigma_c, each its own inverse.
SGCHESS_COMPOSITION_TABLE = (
    (0, 1),
    (1, 0),
)


def compose(g1: int, g2: int) -> int:
    """G_chess composition (kept for backward compatibility)."""
    return COMPOSITION_TABLE[int(g1)][int(g2)]


def inverse(g: int) -> int:
    """Every element of G_chess is its own inverse."""
    return int(g)


@dataclass(frozen=True)
class GroupDef:
    """A lightweight description of a finite group used by the G-CNN
    primitives.

    The composition table is given in the group's own LOCAL enumeration
    (indices ``0..order-1``). The ``to_gchess`` tuple maps each local
    element to a GChess element (as an ``int``) — this is how the
    primitives bridge to the chess-aware actions in ``symmetry.actions``,
    which are defined on GChess.

    Self-inverse property: both GCHESS_GROUP (Klein four) and
    SGCHESS_GROUP (Z_2) consist entirely of involutions, so every
    composition-table row j satisfies ``ct[j][j] == 0``. Other modules
    (e.g. the regular-rep permutation) rely on this.
    """

    name: str
    order: int
    composition_table: Tuple[Tuple[int, ...], ...]
    to_gchess: Tuple[int, ...]

    def __post_init__(self):
        # Cheap structural sanity checks — catch typos in the literal table.
        if len(self.composition_table) != self.order:
            raise ValueError(
                f"composition_table has {len(self.composition_table)} rows, "
                f"expected {self.order}"
            )
        for row in self.composition_table:
            if len(row) != self.order:
                raise ValueError("non-square composition table")
        if len(self.to_gchess) != self.order:
            raise ValueError(
                f"to_gchess has {len(self.to_gchess)} entries, expected {self.order}"
            )

    def compose(self, g1: int, g2: int) -> int:
        return self.composition_table[int(g1)][int(g2)]

    def gchess_element(self, local_g: int) -> int:
        """Return the GChess element (as int) that the local index ``local_g``
        corresponds to. Used by primitives to invoke spatial / chess-aware
        actions in ``symmetry.actions`` that are defined on GChess."""
        return int(self.to_gchess[int(local_g)])


GCHESS_GROUP = GroupDef(
    name="gchess",
    order=ORDER,
    composition_table=COMPOSITION_TABLE,
    to_gchess=(int(GChess.E), int(GChess.SIGMA_H), int(GChess.SIGMA_C), int(GChess.SIGMA_HC)),
)

SGCHESS_GROUP = GroupDef(
    name="sgchess",
    order=SGCHESS_ORDER,
    composition_table=SGCHESS_COMPOSITION_TABLE,
    to_gchess=(int(GChess.E), int(GChess.SIGMA_C)),
)
