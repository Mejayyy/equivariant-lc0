def test_regular_rep_perm_flipgroup_identity():
    perm = regular_rep_perm(FlipGroup.E, num_logical_channels=3, group=FLIPGROUP_GROUP)
    assert torch.equal(perm, torch.arange(3 * ORDER, dtype=torch.long))


def test_regular_rep_perm_flipgroup_sigma_h_swaps_fibers():
    C = 3
    perm = regular_rep_perm(FlipGroup.SIGMA_H, num_logical_channels=C, group=FLIPGROUP_GROUP)
    expected = torch.empty(C * ORDER, dtype=torch.long)
    for c in range(C):
        expected[c * 2 + 0] = c * 2 + 1
        expected[c * 2 + 1] = c * 2 + 0
    assert torch.equal(perm, expected)


def test_regular_rep_perm_flipgroup_self_inverse():
    perm = regular_rep_perm(FlipGroup.SIGMA_H, num_logical_channels=2, group=FLIPGROUP_GROUP)
    assert torch.equal(perm[perm], torch.arange(2 * ORDER, dtype=torch.long))


def test_group_action_g_signal_flipgroup_self_inverse():
    x = torch.randn(2, 3 * ORDER, 8, 8)
    twice = group_action_g_signal(
        FlipGroup.SIGMA_H,
        group_action_g_signal(FlipGroup.SIGMA_H, x, 3, group=FLIPGROUP_GROUP),
        3,
        group=FLIPGROUP_GROUP,
    )
    assert torch.equal(twice, x)


def test_group_action_g_signal_flipgroup_is_file_flip_plus_swap():
    """sigma_h on a FlipGroup signal = spatial file flip + fiber swap."""
    x = torch.randn(1, 2 * ORDER, 8, 8)  # 2 logical channels
    out = group_action_g_signal(FlipGroup.SIGMA_H, x, 2, group=FLIPGROUP_GROUP)
    # Manually: file-flip space, then swap the 2 fibers of each channel.
    flipped = torch.flip(x, dims=[-1])
    expected = torch.empty_like(flipped)
    for c in range(2):
        expected[:, c * 2 + 0] = flipped[:, c * 2 + 1]
        expected[:, c * 2 + 1] = flipped[:, c * 2 + 0]
    assert torch.equal(out, expected)


