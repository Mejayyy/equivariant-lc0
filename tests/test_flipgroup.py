"""FlipGroup ({e, sigma_h}) equivariant-CNN tests.

FlipGroup is the order-2 subgroup of G_chess generated by sigma_h (the
file flip / reflection across the vertical axis). A FlipGroup-equivariant
model (FGCNN = ``GCNNChess(group=FLIPGROUP_GROUP)``) must be strictly
equivariant under sigma_h and is NOT expected to be equivariant under
sigma_c / sigma_hc (those are not FlipGroup elements).

Coverage mirrors the SGChess suite (spread across test_symmetry,
test_gcnn, test_heads, test_equivariance, test_training) but is collected
here in one module:
  - primitives: regular_rep_perm, group_action_g_signal, LiftingConv,
    GConv (incl. a white-box check that the kernel is file-flipped),
    GLinear, GBatchNorm, GSELayer, mini-pipeline.
  - heads: orbit gather invariants, policy/value/mlh heads. The value
    head here runs in INVARIANT mode (sigma_h does not swap W<->L).
  - end-to-end: GCNNChess(group=FLIPGROUP_GROUP) shapes, equivariance,
    NOT-equivariant-under-sigma_c regression, param count.
  - trainer: --model fgcnn wiring.
"""

