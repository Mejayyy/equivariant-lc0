def test_gconv_flipgroup_kernel_uses_file_flip():
    """White-box: the FlipGroup GConv expands its 2 base kernels into the
    big (C_out*2, C_in*2, k, k) Conv2d weight with the sigma_h block
    spatially FILE-flipped."""
    torch.manual_seed(0)
    layer = GConv(in_channels=2, out_channels=2, kernel_size=3, padding=1, group=FLIPGROUP_GROUP)
    big = layer._build_kernel()  # (C_out*2, C_in*2, 3, 3)
    base = layer.weight          # (2, C_out, C_in, 3, 3)
    # Block (g_out, g_in) lives at big[g_out::2, g_in::2].
    assert torch.allclose(big[0::ORDER, 0::ORDER], base[0])                       # (0,0): E
    assert torch.allclose(big[0::ORDER, 1::ORDER], torch.flip(base[1], dims=[-1]))  # (0,1): file flip
    assert torch.allclose(big[1::ORDER, 0::ORDER], base[1])                       # (1,0): E
    assert torch.allclose(big[1::ORDER, 1::ORDER], torch.flip(base[0], dims=[-1]))  # (1,1): file flip


