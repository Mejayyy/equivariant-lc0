def test_equivariant_value_head_flipgroup_is_invariant_mode():
    """FlipGroup has no color swap -> the value head runs in INVARIANT
    mode: color_swap is False and there are THREE independent linears
    (w_linear, l_linear, d_linear), NOT a shared wl_linear."""
    head = EquivariantValueHead(filters=8, group=FLIPGROUP_GROUP)
    assert head.color_swap is False
    assert hasattr(head, "w_linear") and hasattr(head, "l_linear") and hasattr(head, "d_linear")
    assert not hasattr(head, "wl_linear")
    linears = [m for m in head.modules() if isinstance(m, torch.nn.Linear)]
    assert len(linears) == 3
    # The three readouts are genuinely distinct module instances.
    assert len({id(head.w_linear), id(head.l_linear), id(head.d_linear)}) == 3


