def test_fgcnn_not_equivariant_under_sigma_c():
    """FGCNN is FlipGroup-equivariant (sigma_h) but must NOT be equivariant
    under sigma_c / sigma_hc. Run the FULL GChess metric and assert sigma_h
    is tiny while sigma_c and sigma_hc are O(1)."""
    torch.manual_seed(0)
    model = _make_fgcnn()
    errors = equivariance_error(model, n_samples=8, device="cpu")
    assert errors["sigma_h"] < EQUIV_TOL, f"sigma_h should be ~0, got {errors['sigma_h']}"
    assert errors["sigma_c"] > 1e-2, f"sigma_c should be O(1), got {errors['sigma_c']}"
    assert errors["sigma_h_c"] > 1e-2, f"sigma_hc should be O(1), got {errors['sigma_h_c']}"


def test_fgcnn_param_count_matches_sgcnn_order():
    """FGCNN and SGCNN are both |G|=2 models, so at matched (blocks,
    filters, ...) their parameter counts are close and both are well
    below the |G|=4 GCNN. (They differ slightly: FGCNN's value head uses
    3 independent linears in invariant mode vs the shared wl_linear.)"""
    cfg = dict(blocks=2, filters=32, se_channels=8, mlh_channels=8, fc_size=64)
    n_g = sum(p.numel() for p in build_model("gcnn", **cfg).parameters())
    n_s = sum(p.numel() for p in build_model("sgcnn", **cfg).parameters())
    n_f = sum(p.numel() for p in build_model("fgcnn", **cfg).parameters())
    assert n_f < n_g, f"FGCNN ({n_f}) should have far fewer params than GCNN ({n_g})"
    # SGCNN and FGCNN within ~2% of each other (same |G|, near-identical heads).
    assert abs(n_f - n_s) / n_s < 0.02, f"FGCNN {n_f} vs SGCNN {n_s} differ too much"


