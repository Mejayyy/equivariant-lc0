def test_mini_pipeline_flipgroup_equivariance():
    torch.manual_seed(0)
    lift = LiftingConv(in_channels=34, out_channels=5, kernel_size=3, padding=1, group=FLIPGROUP_GROUP)
    bn = GBatchNorm(num_logical_channels=5, group=FLIPGROUP_GROUP)
    gconv = GConv(in_channels=5, out_channels=4, kernel_size=3, padding=1, group=FLIPGROUP_GROUP)
    lift.eval(); bn.eval(); gconv.eval()

    def fwd(z):
        return gconv(torch.nn.functional.relu(bn(lift(z))))

    x = _sample_chess_input(batch=2, seed=0)
    gx = group_action_input(GChess.SIGMA_H, x)
    with torch.no_grad():
        out_x = fwd(x)
        out_gx = fwd(gx)
        g_out_x = group_action_g_signal(FlipGroup.SIGMA_H, out_x, 4, group=FLIPGROUP_GROUP)
    assert (out_gx - g_out_x).abs().max().item() < EQUIV_TOL


